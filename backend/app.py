@app.route("/api/sensor/latest", methods=["GET"])
def get_latest_sensor_data():

    conn = None

    try:

        conn = get_db_connection()

        row = execute_sql(
            conn,
            """
                SELECT *
                FROM sensor_data
                ORDER BY id DESC
                LIMIT 1
            """
        ).fetchone()

        if row is None:

            return jsonify({

                "status": "empty",

                "message": "No sensor readings available"

            }), 404

        return jsonify(dict(row)), 200

    except Exception:

        logger.exception(
            "Failed to retrieve latest sensor reading."
        )

        return jsonify({

            "status": "error",

            "message": "Failed to retrieve latest sensor reading"

        }), 500

    finally:

        if conn:
            conn.close()


