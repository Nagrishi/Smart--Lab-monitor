# ==================================================

def initialize_database():
    """Create the sensor table and add missing columns."""

    database_type = (
        "PostgreSQL" if USE_POSTGRES else "SQLite"
    )

    logger.info(
        "Initializing %s database",
        database_type
    )

    with closing(get_db_connection()) as conn:

        try:

            if USE_POSTGRES:

                execute_sql(conn, """
                    CREATE TABLE IF NOT EXISTS sensor_data (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        temperature DOUBLE PRECISION NOT NULL,
                        humidity DOUBLE PRECISION NOT NULL,
                        "timestamp" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
                    )
                """)

                # Add missing PostgreSQL columns.
                for column, column_type in SENSOR_COLUMNS.items():

                    execute_sql(
                        conn,
                        f"""
                            ALTER TABLE sensor_data
                            ADD COLUMN IF NOT EXISTS
                            {column} {column_type}
                        """
                    )

                # Index for faster timestamp queries.
                execute_sql(conn, """
                    CREATE INDEX IF NOT EXISTS
                    idx_sensor_data_timestamp
                    ON sensor_data ("timestamp" DESC)
                """)

            else:

                execute_sql(conn, """
                    CREATE TABLE IF NOT EXISTS sensor_data (
                        id INTEGER PRIMARY KEY AUTOINCREMENT,
                        temperature REAL NOT NULL,
                        humidity REAL NOT NULL,
                        timestamp DATETIME DEFAULT CURRENT_TIMESTAMP
                    )
                """)

                # Read existing SQLite columns.
                existing_columns = {
                    row["name"]
                    for row in execute_sql(
                        conn,
                        "PRAGMA table_info(sensor_data)"
                    ).fetchall()
                }

                # Add only missing columns.
                for column, column_type in SENSOR_COLUMNS.items():

                    if column not in existing_columns:

                        execute_sql(
                            conn,
                            f"""
                                ALTER TABLE sensor_data
                                ADD COLUMN {column} {column_type}
                            """
                        )

            conn.commit()

            logger.info(
                "Database initialization completed."
            )

        except Exception:

            conn.rollback()

            logger.exception(
                "Database initialization failed."
            )

            raise


