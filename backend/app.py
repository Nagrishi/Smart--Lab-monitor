@app.route("/api/sensor", methods=["GET"])
def get_sensor_data():

    conn = None

    try:

        conn = get_db_connection()

        rows = execute_sql(
            conn,
            """
                SELECT *
                FROM sensor_data
                ORDER BY id DESC
                LIMIT 1000
            """
        ).fetchall()

        return jsonify([dict(row) for row in rows]), 200

    except Exception:

        logger.exception(
            "Failed to retrieve sensor history."
        )

        return jsonify({

            "status": "error",

            "message": "Failed to retrieve sensor data"

        }), 500

    finally:

        if conn:
            conn.close()


