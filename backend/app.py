@app.route("/api/sensor", methods=["POST"])
def receive_sensor_data():

    data = request.get_json(silent=True)

    if not isinstance(data, dict):

        return jsonify({

            "status": "error",

            "message": "A valid JSON object is required"

        }), 400

    # Support flat and nested JSON payloads.
    pzem = data.get("pzem") or {}
    dht11 = data.get("dht11") or {}
    mq2 = data.get("mq2") or {}
    mmwave = data.get("mmwave") or {}
    alerts = data.get("alerts") or {}

    sections = [
        pzem,
        dht11,
        mq2,
        mmwave,
        alerts
    ]

    if not all(
        isinstance(section, dict)
        for section in sections
    ):

        return jsonify({

            "status": "error",

            "message": "Sensor sections must be JSON objects"

        }), 400

    # ------------------------------
    # DHT11
    # ------------------------------

    temperature = to_number(
        dht11.get(
            "temperature",
            data.get("temperature")
        )
    )

    humidity = to_number(
        dht11.get(
            "humidity",
            data.get("humidity")
        )
    )

    if temperature is None or humidity is None:

        return jsonify({

            "status": "error",

            "message": "Temperature and humidity are required"

        }), 400

    # ------------------------------
    # PZEM-004T
    # ------------------------------

    voltage = to_number(
        pzem.get("voltage", data.get("voltage"))
    )

    current = to_number(
        pzem.get("current", data.get("current"))
    )

    power = to_number(
        pzem.get("power", data.get("power"))
    )

    energy = to_number(
        pzem.get("energy", data.get("energy"))
    )

    frequency = to_number(
        pzem.get("frequency", data.get("frequency"))
    )

    power_factor = to_number(
        pzem.get(
            "power_factor",
            data.get("power_factor")
        )
    )

    # ------------------------------
    # MQ-2
    # ------------------------------

    mq2_adc = to_integer(
        mq2.get("adc", data.get("mq2_adc"))
    )

    mq2_voltage = to_number(
        mq2.get("voltage", data.get("mq2_voltage"))
    )

    mq2_digital = to_integer(
        mq2.get("digital", data.get("mq2_digital"))
    )

    # ------------------------------
    # MMWAVE
    # ------------------------------

    person_detected = mmwave.get(
        "person_detected",
        data.get(
            "mmwave_person_detected",
            data.get("person_detected")
        )
    )

    person_detected = to_integer(
        person_detected
    )

    # ------------------------------
    # ALERTS
    # ------------------------------

    gas_triggered = to_integer(
        alerts.get(
            "gas_triggered",
            data.get("gas_triggered")
        )
    )

    temperature_warning = to_integer(
        alerts.get(
            "temperature_warning",
            data.get("temperature_warning")
        )
    )

    buzzer_on = to_integer(
        alerts.get(
            "buzzer_on",
            data.get("buzzer_on")
        )
    )

    # ==================================================
    # SAVE SENSOR DATA
    # ==================================================

    conn = None

    try:

        conn = get_db_connection()

        insert_sql = """
            INSERT INTO sensor_data (
                temperature,
                humidity,
                voltage,
                current,
                power,
                energy,
                frequency,
                power_factor,
                mq2_adc,
                mq2_voltage,
                mq2_digital,
                mmwave_person_detected,
                gas_triggered,
                temperature_warning,
                buzzer_on
            )
            VALUES (
                ?, ?, ?, ?, ?, ?,
                ?, ?, ?, ?, ?, ?, ?, ?, ?
            )
        """

        values = (
            temperature,
            humidity,
            voltage,
            current,
            power,
            energy,
            frequency,
            power_factor,
            mq2_adc,
            mq2_voltage,
            mq2_digital,
            person_detected,
            gas_triggered,
            temperature_warning,
            buzzer_on
        )

        if USE_POSTGRES:
            insert_sql += " RETURNING id"

        cursor = execute_sql(
            conn,
            insert_sql,
            values
        )

        if USE_POSTGRES:
            record_id = cursor.fetchone()["id"]
        else:
            record_id = cursor.lastrowid

        conn.commit()

        logger.info(
            "Sensor record saved. ID=%s Temperature=%s Humidity=%s",
            record_id,
            temperature,
            humidity
        )

        return jsonify({

            "status": "success",

            "message": "Sensor data saved",

            "record_id": record_id

        }), 201

    except Exception:

        if conn:
            conn.rollback()

        logger.exception(
            "Failed to save sensor data."
        )

        return jsonify({

            "status": "error",

            "message": "Failed to save sensor data"

        }), 500

    finally:

        if conn:
            conn.close()


