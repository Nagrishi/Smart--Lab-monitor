def to_number(value):

    if value is None or isinstance(value, bool):
        return None

    try:

        number = float(value)

        return (
            number
            if math.isfinite(number)
            else None
        )

    except (
        ValueError,
        TypeError,
        OverflowError
    ):

        return None


def to_integer(value):

    if value is None:
        return None

    if isinstance(value, bool):
        return int(value)

    if isinstance(value, str):

        value = value.strip().lower()

        if value in ("true", "high", "yes", "on"):
            return 1

        if value in ("false", "low", "no", "off"):
            return 0

    try:

        number = float(value)

        if number in (0, 1):
            return int(number)

    except (
        ValueError,
        TypeError,
        OverflowError
    ):

        pass

    return None


